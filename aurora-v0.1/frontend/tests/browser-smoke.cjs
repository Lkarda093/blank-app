  await page.getByRole('button', {name:'Enviar mensagem'}).click();
  await page.getByText('RESPOSTA SIMULADA DE TESTE: Teste de persistência no navegador', {exact:true}).waitFor();
  await page.getByLabel('Sua mensagem').fill('test-quota');
  await page.getByRole('button', {name:'Enviar mensagem'}).click();
  await page.getByRole('alert').filter({hasText:'Cota simulada'}).waitFor();
  assert.equal(await page.getByLabel('Sua mensagem').inputValue(), 'test-quota');
  await page.getByRole('button', {name:'Alternar tema'}).click();
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'light');
  await page.reload();
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'light');
  await page.getByLabel('Token do proprietário').fill('browser-test-owner-token-0000000000000000');
  await page.getByRole('button', {name:'Entrar no meu espaço'}).click();
  await page.getByRole('button', {name:'Teste de persistência no navegador',exact:true}).click();
  await page.getByText('RESPOSTA SIMULADA DE TESTE: Teste de persistência no navegador',{exact:true}).waitFor();
